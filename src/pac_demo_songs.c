/* =========================================================================
 * Sequencer Engine Implementation
 * ========================================================================= */
void demo_player_init(demo_player_t *player) {
    if (!player) return;
    memset(player, 0, sizeof(*player));
    player->current_song = SONG_NAMCO_NEON;
    player->loop = true;
}

void demo_player_select(demo_player_t *player, demo_song_id_t song_id) {
    if (!player || song_id >= SONG_COUNT) return;
    player->current_song = song_id;
    player->current_step = 0;
    player->tick_counter = 0;
}

void demo_player_play(demo_player_t *player) {
    if (!player) return;
    player->playing = true;
}

void demo_player_stop(demo_player_t *player) {
    if (!player) return;
    player->playing = false;
    player->current_step = 0;
    player->tick_counter = 0;
}

void demo_player_tick(demo_player_t *player) {
    if (!player || !player->playing) return;

    const demo_song_t *song = &g_demo_songs[player->current_song];
    player->tick_counter++;

    /* Standard tick: at 60 Hz frame rate, calculate ticks per 16th note step:
     * ticks_per_step = (60 * 60) / (bpm * 4) = 900 / bpm
     */
    uint16_t step_threshold = (song->bpm > 0) ? (900 / song->bpm) : 6;
    if (step_threshold < 2) step_threshold = 2;

    if (player->tick_counter >= step_threshold) {
        player->tick_counter = 0;
        player->current_step++;
        if (player->current_step >= song->total_steps) {
            if (player->loop) {
                player->current_step = 0;
            } else {
                player->current_step = song->total_steps - 1;
                player->playing = false;
            }
        }
    }
}
